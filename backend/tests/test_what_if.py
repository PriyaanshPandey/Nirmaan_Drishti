def test_risk_score_empirical_percentile_normalization():
    """
    Test 8: Risk score uses empirical percentile normalization, remains strictly 0-100,
    and higher predicted cost overrun / schedule delay never reduces risk (monotonicity).
    """
    # 1. Monotonicity of percentile_rank
    cost_test_vals = [-50.0, 0.0, 2.0, 10.0, 25.0, 50.0, 100.0, 500.0, 5000.0]
    prev_pct = -1.0
    for c in cost_test_vals:
        pct = percentile_rank(c, COST_OVERRUN_QUANTILES)
        assert 0.0 <= pct <= 1.0, f"Percentile rank {pct} out of [0, 1] range"
        assert pct >= prev_pct, f"Percentile rank decreased from {prev_pct} to {pct} at cost {c}"
        prev_pct = pct

    delay_test_vals = [-10.0, 0.0, 1.0, 6.0, 12.0, 24.0, 48.0, 100.0, 400.0]
    prev_pct = -1.0
    for d in delay_test_vals:
        pct = percentile_rank(d, SCHEDULE_DELAY_QUANTILES)
        assert 0.0 <= pct <= 1.0, f"Percentile rank {pct} out of [0, 1] range"
        assert pct >= prev_pct, f"Percentile rank decreased from {prev_pct} to {pct} at delay {d}"
        prev_pct = pct

    # 2. Risk Score monotonicity and bounds
    prev_score = -1.0
    for c in cost_test_vals:
        res = calculate_risk_score(c, 12.0)
        assert 0.0 <= res.risk_score <= 100.0
        assert res.risk_score >= prev_score
        prev_score = res.risk_score

    # 3. Configurable weights
    custom_res = calculate_risk_score(25.0, 12.0, weight_cost=0.70, weight_schedule=0.30)
    assert 0.0 <= custom_res.risk_score <= 100.0


