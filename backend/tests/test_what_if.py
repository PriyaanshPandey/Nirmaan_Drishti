def test_canonical_schedule_delay_artifact_and_synchronization():
    """
    Test 14: Verify that the loaded schedule delay model artifact corresponds
    to the final xgb_del model saved as best_model_schedule_delay.json from train_models.py,
    and is strictly synchronized across results/best_model and ai/models.
    """
    import json
    import hashlib
    import xgboost as xgb

    best_model_path = backend_dir.parent / "results" / "best_model" / "best_model_schedule_delay.json"
    ai_model_path = backend_dir.parent / "ai" / "models" / "best_model_schedule_delay.json"

    assert best_model_path.exists(), f"Canonical model artifact missing at {best_model_path}"
    assert ai_model_path.exists(), f"Synchronized model artifact missing at {ai_model_path}"

    # Verify bit-for-bit synchronization
    best_bytes = best_model_path.read_bytes()
    ai_bytes = ai_model_path.read_bytes()
    sha_best = hashlib.sha256(best_bytes).hexdigest()
    sha_ai = hashlib.sha256(ai_bytes).hexdigest()
    assert sha_best == sha_ai, f"Artifact desynchronization: {sha_best} != {sha_ai}"

    # Verify model architecture corresponds to final xgb_del from train_models.py
    # xgb_del was trained with n_estimators=260, learning_rate=0.035, max_depth=6 on delta_del
    with open(best_model_path, "r", encoding="utf-8") as f:
        model_meta = json.load(f)

    # 1. Booster rounds verification (260 trees)
    booster = xgb.Booster()
    booster.load_model(str(best_model_path))
    assert booster.num_boosted_rounds() == 260, (
        f"Expected 260 boosted rounds from final train_models.py, got {booster.num_boosted_rounds()}"
    )

    # 2. Base score verification:
    # Training semantics: delta_delay = target_future_delay - current_delay
    # The average delta in train set is ~1.28 months, whereas total delay would be >15 months.
    learner_param = model_meta.get("learner", {}).get("learner_model_param", {})
    base_score_str = learner_param.get("base_score", "")
    cleaned_score = float(base_score_str.strip("[]"))
    assert 0.5 < cleaned_score < 5.0, (
        f"base_score {cleaned_score} does not match delta_delay semantics (~1.28). "
        "It appears trained on raw total delay instead of delta!"
    )

    # 3. Model loaded in ai_engine corresponds to this canonical model
    ai_engine._ensure_initialized()
    assert "best_model_schedule_delay" in ai_engine.models
    assert "xgb_schedule_model" in ai_engine.models
    loaded_booster = ai_engine.models["xgb_schedule_model"].get_booster()
    assert loaded_booster.num_boosted_rounds() == 260


def test_authoritative_schedule_reconstruction_semantics(db_session):
    """
    Test 15: Verify authoritative training and inference semantics:
    target_future_delay = current_delay + predicted_delta
    Model trained on: delta_delay = target_future_delay - current_delay
    Inference:
    predicted_delta = xgb_schedule_model.predict(features)
    predicted_total_delay = scenario_current_delay + predicted_delta

    CRITICAL: Raw XGBoost output must NEVER be treated as total delay.
    """
    from src.predict import predict_time
    from src.project_service import prepare_prediction_features, get_current_status

    ai_engine._ensure_initialized()
    df_to_use = ai_engine._get_df_for_project(SAMPLE_PID)
    current = get_current_status(SAMPLE_PID, df_to_use)
    features_df = prepare_prediction_features(SAMPLE_PID, df_to_use)

    # Define a scenario with an explicit current schedule extension
    scen_current_delay = 14.5
    scen_current = current.copy()
    scen_current["schedule_extension_months"] = scen_current_delay

    scen_features = features_df.copy()
    scen_features["schedule_extension_months"] = scen_current_delay

    time_pred = predict_time(scen_features, ai_engine.models, scen_current, horizons=[3])
    h3 = time_pred["3_month"]

    predicted_delta = h3["predicted_additional_delay_months"]
    predicted_total_delay = h3["predicted_total_schedule_extension_months"]

    # Explicit check 1: Model predictions are valid floats
    assert isinstance(predicted_delta, float)
    assert isinstance(predicted_total_delay, float)

    # Explicit check 2: Reconstruction follows target_future_delay = current_delay + predicted_delta
    expected_total = round(scen_current_delay + predicted_delta, 2)
    assert predicted_total_delay == expected_total, (
        f"Reconstruction mismatch: {predicted_total_delay} != {expected_total} "
        f"(scenario_current_delay={scen_current_delay}, predicted_delta={predicted_delta})"
    )

    # Explicit check 3: Raw XGBoost output is NOT treated as total delay
    assert predicted_total_delay != predicted_delta, (
        "CRITICAL ERROR: Raw XGBoost output was treated directly as total delay! "
        f"predicted_total_delay ({predicted_total_delay}) == predicted_delta ({predicted_delta})"
    )


def test_what_if_schedule_simulation_pipeline_reconstruction(db_session):
    """
    Test 16: Verify that the What-If simulation service pipeline enforces the exact
    schedule reconstruction:
    predicted_total_delay = scenario_current_delay + predicted_delta
    and that impact deltas match the difference.
    """
    base_req = WhatIfRequest(additional_cost=0.0, additional_delay_months=0.0)
    base_res = simulate_project_scenario(SAMPLE_PID, base_req, db_session)

    # Add 9.5 months of additional delay
    add_delay = 9.5
    scen_req = WhatIfRequest(additional_cost=0.0, additional_delay_months=add_delay)
    scen_res = simulate_project_scenario(SAMPLE_PID, scen_req, db_session)

    # Check baseline delay reconstruction
    assert scen_res.scenario.predicted_schedule_delay >= scen_res.baseline.predicted_schedule_delay
    assert scen_res.impact.schedule_delay_change == round(
        scen_res.scenario.predicted_schedule_delay - scen_res.baseline.predicted_schedule_delay, 2
    )

    # Check PDP for schedule uses x_val + predicted_delta
    pdp_sched = scen_res.pdp_schedule
    for pt in pdp_sched.points:
        assert pt.y >= 0.0

